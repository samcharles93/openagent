#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const EXTENSION_NAME = "openagent";

function parseArgs(argv) {
  let force = false;
  let targetDir;

  for (const arg of argv) {
    if (arg === "--force") {
      force = true;
      continue;
    }

    if (arg.startsWith("--target-dir=")) {
      const value = arg.slice("--target-dir=".length).trim();
      if (value.length > 0) {
        targetDir = path.resolve(value);
      }
    }
  }

  return { force, targetDir };
}

function getDefaultExtensionsDir() {
  const configuredDir = process.env.COPILOT_EXTENSIONS_DIR?.trim();
  if (configuredDir) {
    return path.resolve(configuredDir);
  }

  return path.join(os.homedir(), ".copilot", "extensions");
}

function main() {
  const scriptPath = fileURLToPath(import.meta.url);
  const repoRoot = path.resolve(path.dirname(scriptPath), "..");
  const sourceEntry = path.join(
    repoRoot,
    ".github",
    "extensions",
    EXTENSION_NAME,
    "extension.mjs",
  );
  const { force, targetDir } = parseArgs(process.argv.slice(2));
  const extensionsDir = targetDir ?? getDefaultExtensionsDir();
  const installDir = path.join(extensionsDir, EXTENSION_NAME);
  const installEntry = path.join(installDir, "extension.mjs");
  const metadataPath = path.join(installDir, "openagent-install.json");

  if (!existsSync(sourceEntry)) {
    throw new Error(
      [
        "OpenAgent build output is missing.",
        `Expected: ${sourceEntry}`,
        "Run `npm run build` first, or use `npm run setup:copilot`.",
      ].join("\n"),
    );
  }

  const wrapperSource = [
    "// Generated by scripts/setup-copilot-extension.mjs",
    `import ${JSON.stringify(pathToFileURL(sourceEntry).href)};`,
    "",
  ].join("\n");

  const metadata = JSON.stringify(
    {
      name: EXTENSION_NAME,
      repoRoot,
      sourceEntry,
      installedAt: new Date().toISOString(),
      installMode: "wrapper-import",
    },
    null,
    2,
  ).concat("\n");

  const alreadyInstalled =
    existsSync(installEntry) && readFileSync(installEntry, "utf8") === wrapperSource;

  if (alreadyInstalled && !force) {
    process.stdout.write(
      [
        `OpenAgent is already installed for Copilot CLI at ${installDir}.`,
        "Nothing changed.",
        "",
        "Next steps:",
        "1. Start `copilot` in any repo.",
        "2. Run `/env` or `/statusline` if you want to confirm the extension is loaded.",
        "3. Use `/oa-start <request>` to bootstrap OpenAgent work.",
        "",
        "Use `npm run setup:copilot -- --force` to refresh the wrapper after moving the repo.",
      ].join("\n"),
    );
    return;
  }

  if (existsSync(installDir) && force) {
    rmSync(installDir, { recursive: true, force: true });
  }

  mkdirSync(installDir, { recursive: true });
  writeFileSync(installEntry, wrapperSource, "utf8");
  writeFileSync(metadataPath, metadata, "utf8");

  process.stdout.write(
    [
      `Installed OpenAgent into Copilot's user extensions directory: ${installDir}`,
      `Source extension: ${sourceEntry}`,
      "",
      "Copilot CLI discovers user extensions from ~/.copilot/extensions/<name>/extension.mjs.",
      "This install writes a thin wrapper there that imports the built extension from this repo.",
      "",
      "Next steps:",
      "1. Restart `copilot`, or run `/clear` in an existing session to reload extensions.",
      "2. Start work with `/oa-start <request>`.",
      "3. When you rebuild or move this repo, rerun `npm run setup:copilot`.",
    ].join("\n"),
  );
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
}
