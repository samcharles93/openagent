#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const EXTENSION_NAME = "openagent";

function parseArgs(argv) {
  let force = false;
  let targetDir;

  for (const arg of argv) {
    if (arg === "--force") {
      force = true;
      continue;
    }

    if (arg.startsWith("--target-dir=")) {
      const value = arg.slice("--target-dir=".length).trim();
      if (value.length > 0) {
        targetDir = path.resolve(value);
      }
    }
  }

  return { force, targetDir };
}

function getDefaultExtensionsDir() {
  const configuredDir = process.env.COPILOT_EXTENSIONS_DIR?.trim();
  if (configuredDir) {
    return path.resolve(configuredDir);
  }

  return path.join(os.homedir(), ".copilot", "extensions");
}

function main() {
  const scriptPath = fileURLToPath(import.meta.url);
  const repoRoot = path.resolve(path.dirname(scriptPath), "..");
  const sourceEntry = path.join(
    repoRoot,
    "src",
    "extension.mts",
  );
  const { force, targetDir } = parseArgs(process.argv.slice(2));
  const extensionsDir = targetDir ?? getDefaultExtensionsDir();
  const installDir = path.join(extensionsDir, EXTENSION_NAME);
  const installEntry = path.join(installDir, "extension.mjs");
  const metadataPath = path.join(installDir, "openagent-install.json");

  if (!existsSync(sourceEntry)) {
    throw new Error(
      [
        "OpenAgent extension entry point is missing.",
        `Expected: ${sourceEntry}`,
        "Run `bun run setup:copilot` to reinstall.",
      ].join("\n") + "\n",
    );
  }

  const wrapperSource = [
    "// Generated by scripts/setup-copilot-extension.mjs",
    "// Auto-reinstalls if source version fingerprint changes",
    `import { readFileSync, existsSync, mkdirSync, rmSync, writeFileSync, statSync } from "node:fs";`,
    `import { createHash } from "node:crypto";`,
    `import path from "node:path";`,
    `import { fileURLToPath } from "node:url";`,
    ``,
    `const SOURCE_VERSION = ${JSON.stringify(SOURCE_VERSION)};`,
    `const SOURCE_FINGERPRINT = ${JSON.stringify(SOURCE_FINGERPRINT)};`,
    ``,
    `function getInstalledWrapperPath() {`,
    `  const meta = import.meta.url;`,
    `  return fileURLToPath(meta);`,
    `}`,
    ``,
    `function checkAndReinstall() {`,
    `  try {`,
    `    const srcEntry = ${JSON.stringify(sourceEntry)};`,
    `    const installDir = path.dirname(getInstalledWrapperPath());`,
    `    const metadataPath = path.join(installDir, "openagent-install.json");`,
    ``,
    `    let needsReinstall = false;`,
    `    try {`,
    `      const meta = existsSync(metadataPath) ? JSON.parse(readFileSync(metadataPath, "utf8")) : {};`,
    `      if (meta.sourceFingerprint !== SOURCE_FINGERPRINT) needsReinstall = true;`,
    `    } catch { needsReinstall = true; }`,
    ``,
    `    if (!needsReinstall) return;`,
    ``,
    `    const wrapperContent = [`,
    `      "// Generated - do not edit",`,
    `      \`import \${JSON.stringify(pathToFileURL(srcEntry).href)};\`,`,
    `      "",`,
    `    ].join("\\n");`,
    ``,
    `    if (existsSync(installDir)) rmSync(installDir, { recursive: true, force: true });`,
    `    mkdirSync(installDir, { recursive: true });`,
    `    writeFileSync(getInstalledWrapperPath(), wrapperContent, "utf8");`,
    `    writeFileSync(metadataPath, JSON.stringify({`,
    `      sourceFingerprint: SOURCE_FINGERPRINT,`,
    `      installedAt: new Date().toISOString(),`,
    `    }, null, 2) + "\\n", "utf8");`,
    `  } catch (e) {`,
    `    // Reinstall check failed - continue anyway`,
    `  }`,
    `}`,
    ``,
    `checkAndReinstall();`,
    `import ${JSON.stringify(pathToFileURL(sourceEntry).href)};`,
    "",
  ].join("\n");

  const metadata = JSON.stringify(
    {
      name: EXTENSION_NAME,
      repoRoot,
      sourceEntry,
      installedAt: new Date().toISOString(),
      installMode: "wrapper-import",
    },
    null,
    2,
  ).concat("\n");

  const alreadyInstalled =
    existsSync(installEntry) && readFileSync(installEntry, "utf8") === wrapperSource;

  if (alreadyInstalled && !force) {
    process.stdout.write(
      [
        `OpenAgent is already installed for Copilot CLI at ${installDir}.`,
        "",
        "Next steps:",
        "1. Start `copilot` in any repo.",
        "2. Run `/env` or `/statusline` if you want to confirm the extension is loaded.",
        "3. Use `/oa-start <request>` to bootstrap OpenAgent work.",
        "4. Run `bun run scripts/setup-copilot-agents.mjs` if native custom agents are missing.",
        "",
        "Use `bun run setup:copilot -- --force` to refresh the wrapper after moving the repo.",
      ].join("\n"),
    );
    return;
  }

  if (existsSync(installDir)) {
    rmSync(installDir, { recursive: true, force: true });
  }

  mkdirSync(installDir, { recursive: true });
  writeFileSync(installEntry, wrapperSource, "utf8");
  writeFileSync(metadataPath, metadata, "utf8");

  process.stdout.write(
    [
      `Installed OpenAgent into Copilot's user extensions directory: ${installDir}`,
      `Source extension: ${sourceEntry}`,
      "",
      "Copilot CLI discovers user extensions from ~/.copilot/extensions/<name>/extension.mjs.",
      "This install writes a thin wrapper there that imports the built extension from this repo.",
      "",
      "Next steps:",
      "1. Restart `copilot`, or run `/clear` in an existing session to reload extensions.",
      "2. Start work with `/oa-start <request>`.",
      "3. Run `bun run scripts/setup-copilot-agents.mjs` if native custom agents are missing.",
      "4. When you move this repo, rerun `bun run setup:copilot`.",
    ].join("\n") + "\n",
  );
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
}
