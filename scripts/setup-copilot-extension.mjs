#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const EXTENSION_NAME = "openagent";

function findBun() {
  if (process.env.BUN_INSTALL) {
    const candidate = path.join(process.env.BUN_INSTALL.trim(), "bin", "bun");
    if (existsSync(candidate)) return candidate;
  }
  for (const candidate of [
    path.join(os.homedir(), ".bun", "bin", "bun"),
    path.join(os.homedir(), ".local", "bin", "bun"),
    "/usr/local/bin/bun",
    "/usr/bin/bun",
  ]) {
    if (existsSync(candidate)) return candidate;
  }
  return "bun";
}

function bundleExtension(repoRoot) {
  const srcEntry = path.join(repoRoot, "src", "extension.mts");
  const distEntry = path.join(repoRoot, "dist", "extension.mjs");
  const bun = findBun();

  process.stdout.write(`Bundling extension: ${srcEntry} → ${distEntry}\n`);

  const result = spawnSync(
    bun,
    [
      "build",
      srcEntry,
      "--outfile",
      distEntry,
      "--target",
      "node",
      "--format",
      "esm",
      "--external",
      "@github/copilot-sdk",
      "--external",
      "@github/copilot-sdk/extension",
      "--external",
      "typescript",
      "--external",
      "jsonc-parser",
    ],
    { stdio: "inherit", cwd: repoRoot },
  );

  if (result.error) {
    throw new Error(
      `Failed to run bun build: ${result.error.message}\nIs bun installed? https://bun.sh`,
    );
  }

  if (result.status !== 0) {
    throw new Error(`bun build failed with exit code ${result.status}`);
  }

  if (!existsSync(distEntry)) {
    throw new Error(`Bundle was not created at ${distEntry}`);
  }

  return distEntry;
}

function parseArgs(argv) {
  let force = false;
  let targetDir;

  for (const arg of argv) {
    if (arg === "--force") {
      force = true;
      continue;
    }

    if (arg.startsWith("--target-dir=")) {
      const value = arg.slice("--target-dir=".length).trim();
      if (value.length > 0) {
        targetDir = path.resolve(value);
      }
    }
  }

  return { force, targetDir };
}

function getDefaultExtensionsDir() {
  const configuredDir = process.env.COPILOT_EXTENSIONS_DIR?.trim();
  if (configuredDir) {
    return path.resolve(configuredDir);
  }

  return path.join(os.homedir(), ".copilot", "extensions");
}

function main() {
  const scriptPath = fileURLToPath(import.meta.url);
  const repoRoot = path.resolve(path.dirname(scriptPath), "..");
  const srcEntry = path.join(repoRoot, "src", "extension.mts");
  const { force, targetDir } = parseArgs(process.argv.slice(2));
  const extensionsDir = targetDir ?? getDefaultExtensionsDir();
  const installDir = path.join(extensionsDir, EXTENSION_NAME);
  const installEntry = path.join(installDir, "extension.mjs");
  const metadataPath = path.join(installDir, "openagent-install.json");

  if (!existsSync(srcEntry)) {
    throw new Error(
      [
        "OpenAgent extension source is missing.",
        `Expected: ${srcEntry}`,
        "Ensure the repo is intact before running setup.",
      ].join("\n") + "\n",
    );
  }

  // Always bundle so the dist is never stale relative to source.
  const sourceEntry = bundleExtension(repoRoot);

  const SOURCE_VERSION = "1";
  const packageJsonPath = path.join(repoRoot, "package.json");
  const packageVersion = existsSync(packageJsonPath)
    ? JSON.parse(readFileSync(packageJsonPath, "utf8")).version
    : SOURCE_VERSION;
  const SOURCE_FINGERPRINT = createHash("sha256")
    .update(JSON.stringify({ version: packageVersion, fingerprint: SOURCE_VERSION, sourceEntry }))
    .digest("hex")
    .slice(0, 16);

  const wrapperSource = [
    "// Generated by scripts/setup-copilot-extension.mjs",
    "// Auto-reinstalls if source version or path changes",
    `import { spawnSync } from "node:child_process";`,
    `import { existsSync, readFileSync, writeFileSync } from "node:fs";`,
    `import path from "node:path";`,
    `import { fileURLToPath, pathToFileURL } from "node:url";`,
    "",
    `const SOURCE_VERSION = ${JSON.stringify(SOURCE_VERSION)};`,
    `const SOURCE_FINGERPRINT = ${JSON.stringify(SOURCE_FINGERPRINT)};`,
    `const SRC_ENTRY = ${JSON.stringify(sourceEntry)};`,
    "",
    `function checkAndReinstall() {`,
    `  try {`,
    `    const installDir = path.dirname(fileURLToPath(import.meta.url));`,
    `    const metadataPath = path.join(installDir, "openagent-install.json");`,
    "",
    `    let needsReinstall = false;`,
    `    try {`,
    `      const meta = existsSync(metadataPath) ? JSON.parse(readFileSync(metadataPath, "utf8")) : {};`,
    `      if (meta.sourceFingerprint !== SOURCE_FINGERPRINT) needsReinstall = true;`,
    `      if (meta.sourceEntry !== SRC_ENTRY) needsReinstall = true;`,
    `    } catch { needsReinstall = true; }`,
    "",
    `    if (!needsReinstall) return;`,
    "",
    `    const repoRoot = path.dirname(path.dirname(SRC_ENTRY));`,
    `    const setupScript = path.join(repoRoot, "scripts", "setup-copilot-extension.mjs");`,
    `    if (!existsSync(setupScript)) {`,
    `      console.error("[openagent] Setup script not found at " + setupScript);`,
    `      console.error("[openagent] Run 'bun run setup:copilot -- --force' from the repo root.");`,
    `      return;`,
    `    }`,
    `    const result = spawnSync(process.execPath, [setupScript, "--force", "--target-dir=" + installDir], { stdio: "inherit" });`,
    `    if (result.status === 0) process.exit(0);`,
    `    console.error("[openagent] Auto-reinstall failed (exit " + result.status + "). Falling back to direct load.");`,
    `  } catch (e) {`,
    `    console.error("[openagent] Reinstall check failed: " + (e?.message ?? e));`,
    `  }`,
    `}`,
    "",
    `checkAndReinstall();`,
    "",
    `if (!existsSync(SRC_ENTRY)) {`,
    `  console.error("[openagent] Bundle not found at " + SRC_ENTRY);`,
    `  console.error("[openagent] Run 'bun run setup:copilot' from the repo root to rebuild.");`,
    `  process.exit(1);`,
    `}`,
    "",
    `await import(pathToFileURL(SRC_ENTRY).href);`,
    "",
  ].join("\n");

  const metadata = JSON.stringify(
    {
      name: EXTENSION_NAME,
      repoRoot,
      sourceEntry,
      sourceFingerprint: SOURCE_FINGERPRINT,
      installedAt: new Date().toISOString(),
      installMode: "bundled",
    },
    null,
    2,
  ).concat("\n");

  const alreadyInstalled =
    existsSync(installEntry) && readFileSync(installEntry, "utf8") === wrapperSource;

  if (alreadyInstalled && !force) {
    process.stdout.write(
      [
        `OpenAgent is already installed for Copilot CLI at ${installDir}.`,
        "",
        "Next steps:",
        "1. Start `copilot` in any repo.",
        "2. Run `/env` or `/statusline` if you want to confirm the extension is loaded.",
        "3. Use `/oa-start <request>` to bootstrap OpenAgent work.",
        "4. Run `bun run scripts/setup-copilot-agents.mjs` if native custom agents are missing.",
        "",
        "Use `bun run setup:copilot -- --force` to refresh the wrapper after moving the repo.",
      ].join("\n"),
    );
    return;
  }

  if (existsSync(installDir)) {
    rmSync(installDir, { recursive: true, force: true });
  }

  mkdirSync(installDir, { recursive: true });
  writeFileSync(installEntry, wrapperSource, "utf8");
  writeFileSync(metadataPath, metadata, "utf8");

  process.stdout.write(
    [
      `Installed OpenAgent into Copilot's user extensions directory: ${installDir}`,
      `Source extension: ${sourceEntry}`,
      "",
      "Copilot CLI discovers user extensions from ~/.copilot/extensions/<name>/extension.mjs.",
      "This install writes a thin wrapper there that imports the built extension from this repo.",
      "",
      "Next steps:",
      "1. Restart `copilot`, or run `/clear` in an existing session to reload extensions.",
      "2. Start work with `/oa-start <request>`.",
      "3. Run `bun run scripts/setup-copilot-agents.mjs` if native custom agents are missing.",
      "4. When you move this repo, rerun `bun run setup:copilot`.",
    ].join("\n") + "\n",
  );
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
}
